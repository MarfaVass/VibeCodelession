"""
Домашнее задание: монолитный скрипт "Заметки".

Всё в одном файле: список заметок хранится в памяти,
меню работает в бесконечном цикле до выбора "Выход".
"""

# Список заметок (каждая заметка — строка текста)
notes = []


def add_note():
    """Добавляет заметку (строку текста) в список."""
    text = input("Введите текст заметки: ").strip()

    # Проверка: нельзя добавить пустую строку
    if not text:
        print("Ошибка: заметка не может быть пустой.")
        return

    notes.append(text)
    print(f"Заметка добавлена (№ {len(notes)}).")


def show_notes():
    """Выводит все заметки на экран с нумерацией."""
    # Проверка: список пуст — выводить нечего
    if not notes:
        print("Список заметок пуст.")
        return

    print("\n--- Все заметки ---")
    for number, text in enumerate(notes, start=1):
        print(f"{number}. {text}")
    print("-------------------")


def delete_note():
    """Удаляет заметку по её номеру."""
    # Проверка: удалять нечего, если список пуст
    if not notes:
        print("Ошибка: список заметок пуст — удалять нечего.")
        return

    show_notes()
    raw = input("Введите номер заметки для удаления: ").strip()

    # Проверка: пользователь ввёл не число
    if not raw.isdigit():
        print("Ошибка: нужно ввести целое число (номер заметки).")
        return

    number = int(raw)

    # Проверка: номер за пределами списка
    if not 1 <= number <= len(notes):
        print(f"Ошибка: заметки с номером {number} нет. "
              f"Допустимые номера: 1–{len(notes)}.")
        return

    deleted = notes.pop(number - 1)  # в списке нумерация с нуля
    print(f"Удалена заметка № {number}: «{deleted}».")


def main():
    """Точка входа: бесконечный цикл с меню."""
    while True:
        print("\n======= МЕНЮ ========")
        print("1. Добавить заметку")
        print("2. Вывести все заметки")
        print("3. Удалить заметку по номеру")
        print("4. Выход")
        print("=====================")

        choice = input("Выберите пункт меню (1–4): ").strip()

        if choice == "1":
            add_note()
        elif choice == "2":
            show_notes()
        elif choice == "3":
            delete_note()
        elif choice == "4":
            print("Выход. До встречи!")
            break  # выходим из бесконечного цикла
        else:
            # Проверка: неизвестный пункт меню
            print("Ошибка: такого пункта меню нет, введите число от 1 до 4.")


if __name__ == "__main__":
    main()
